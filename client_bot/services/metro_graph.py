# ---------------------------------------------------------------------------
# Строим граф (ненаправленный, однократно, при импорте)
# ---------------------------------------------------------------------------


def _build_graph(edges: list[tuple[str, str]]) -> dict[str, frozenset[str]]:
    raw: dict[str, set[str]] = {}
    for a, b in edges:
        ak, bk = a.strip().lower(), b.strip().lower()
        raw.setdefault(ak, set()).add(bk)
        raw.setdefault(bk, set()).add(ak)
    return {k: frozenset(v) for k, v in raw.items()}


TRANSFER_GRAPH: dict[str, frozenset[str]] = _build_graph(_RAW_EDGES)

# Максимальная глубина BFS (нет смысла считать >6 пересадок)
_MAX_BFS_DEPTH = 6


# ---------------------------------------------------------------------------
# Публичная функция
# ---------------------------------------------------------------------------


def metro_transfer_distance(station_a: str, station_b: str) -> int | None:
    """
    Минимальное количество переходов между двумя станциями.

    Возвращает:
        0    — одинаковые названия (сама с собой)
        1    — прямой переход (рядом, один коридор)
        N    — N шагов по графу
        None — маршрут не найден (станции в разных частях города без связи в графе)

    Регистр и пробельные символы игнорируются.
    """
    if not station_a or not station_b:
        return None
    a = station_a.strip().lower()
    b = station_b.strip().lower()
    if a == b:
        return 0

    queue: deque[tuple[str, int]] = deque([(a, 0)])
    visited: set[str] = {a}

    while queue:
        current, dist = queue.popleft()
        if dist >= _MAX_BFS_DEPTH:
            continue
        for neighbor in TRANSFER_GRAPH.get(current, frozenset()):
            if neighbor == b:
                return dist + 1
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, dist + 1))

    return None
